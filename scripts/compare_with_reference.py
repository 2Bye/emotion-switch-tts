"""Compare this repository's CPU evaluation with what the GPU node measured on the same clips.

    python scripts/compare_with_reference.py

Reads results/baseline/rows.jsonl and data/reference/<run>.jsonl, writes results/baseline/agreement.md.
The node rows come from the source project's own scripts; this repository's code is a port of them.
What is compared is therefore the measured quantities (window grid, arousal, boundary time, step,
transcript) and the detector decision that this repository's rule gives on each side's step.
It checks the port and the hardware independence, not the validity of the measure.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

import numpy as np

from emoswitch import detect
from emoswitch.config import ROOT, load_config
from emoswitch.report import table
from emoswitch.stimuli import NULL_CONDITIONS


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def decision(condition: str, step: dict | None, cfg: dict) -> bool:
    dc = cfg["detector"]
    test = detect.exceeds_null if condition in NULL_CONDITIONS else detect.is_detected
    return test(step, dc["min_abs_delta"], dc["max_changepoint_err_s"])


def compare(cfg: dict) -> tuple[list[dict], list[str]]:
    ours = read_jsonl(ROOT / f"results/{cfg['name']}/rows.jsonl")
    reference = {}
    for path in sorted((ROOT / "data/reference").glob("*.jsonl")):
        reference.update({(r["run"], r["id"]): r for r in read_jsonl(path)})
    per_run, mismatches, unreferenced = defaultdict(lambda: defaultdict(list)), [], defaultdict(int)
    for r in ours:
        ref = reference.get((r["run"], r["id"]))
        if ref is None:  # a run rendered by this repository's generator was never measured on the node
            unreferenced[r["run"]] += 1
            continue
        stat = per_run[r["run"]]
        a, b = np.asarray(r["profile_arousal"]), np.asarray(ref["profile_arousal"])
        stat["same_grid"].append(r["profile_centres_s"] == ref["profile_centres_s"])
        if len(a) == len(b):
            stat["arousal_diff"].extend(np.abs(a - b).tolist())
        if r["step"] and ref["step"]:
            stat["delta_diff"].append(abs(r["step"]["delta"] - ref["step"]["delta"]))
            if r["switch_time_source"] == "forced_alignment":
                stat["time_diff"].append(abs(r["step"]["switch_time_s"] - ref["step"]["switch_time_s"]))
        same = decision(r["condition"], r["step"], cfg) == decision(r["condition"], ref["step"], cfg)
        stat["same_decision"].append(same)
        if not same:
            mismatches.append(f"{r['run']}/{r['id']}: decision differs (ours {r['step']}, node {ref['step']})")
        stat["wer_diff"].append(abs(r["wer"] - ref["wer_target"]))
        stat["same_leak"].append(r["leak"] == ref["prefix_leakage"])
    summary = []
    for run, s in per_run.items():
        summary.append(
            {
                "run": run,
                "n": len(s["same_decision"]),
                "same_grid": int(sum(s["same_grid"])),
                "arousal_max": max(s["arousal_diff"]),
                "arousal_mean": float(np.mean(s["arousal_diff"])),
                "time_max": max(s["time_diff"]) if s["time_diff"] else None,
                "delta_max": max(s["delta_diff"]),
                "same_decision": int(sum(s["same_decision"])),
                "wer_equal": int(sum(d == 0 for d in s["wer_diff"])),
                "wer_max": max(s["wer_diff"]),
                "same_leak": int(sum(s["same_leak"])),
            }
        )
    return summary, mismatches, dict(unreferenced)


def main() -> None:
    cfg = load_config("configs/baseline.yaml")
    summary, mismatches, unreferenced = compare(cfg)
    rows = [
        [
            s["run"],
            str(s["n"]),
            f"{s['same_grid']}/{s['n']}",
            f"{s['arousal_max']:.4f}",
            f"{s['arousal_mean']:.5f}",
            "n/a (by construction)" if s["time_max"] is None else f"{s['time_max']:.3f}",
            f"{s['delta_max']:.4f}",
            f"{s['same_decision']}/{s['n']}",
            f"{s['wer_equal']}/{s['n']}",
            f"{s['wer_max']:.3f}",
            f"{s['same_leak']}/{s['n']}",
        ]
        for s in summary
    ]
    header = ["run", "clips", "same window grid", "max abs arousal diff", "mean abs arousal diff",
              "max boundary time diff, s", "max abs step diff", "same detector decision", "same WER",
              "max abs WER diff", "same leak flag"]  # fmt: skip
    text = (
        "# Agreement with the measurements of the GPU node\n\n"
        "Generated by `python scripts/compare_with_reference.py`; do not edit by hand.\n\n## Per run\n\n"
        + table(header, rows)
        + "\n\n"
        + ("All detector decisions agree.\n" if not mismatches else "\n".join(f"- {m}" for m in mismatches) + "\n")
        + (
            "\nNot measured on the node (rendered by this repository's generator): "
            + ", ".join(f"{run} ({n} clips)" for run, n in unreferenced.items())
            + ".\n"
            if unreferenced
            else ""
        )
    )
    out = ROOT / f"results/{cfg['name']}/agreement.md"
    out.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
